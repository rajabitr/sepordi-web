import { describe, expect, it } from "vitest";

import { mobileToE164, normalizeMobile } from "./phone";

describe("normalizeMobile", () => {
  it.each([
    ["09123456789", "09123456789"],
    ["۰۹۱۲۳۴۵۶۷۸۹", "09123456789"],
    ["٠٩١٢٣٤٥٦٧٨٩", "09123456789"],
    ["+989123456789", "09123456789"],
    ["+98 912 345 6789", "09123456789"],
    ["00989123456789", "09123456789"],
    ["989123456789", "09123456789"],
    ["9123456789", "09123456789"],
    ["0912-345-6789", "09123456789"],
    ["(0912) 345 6789", "09123456789"],
  ])("%s → %s", (input, want) => {
    expect(normalizeMobile(input)).toBe(want);
  });

  it.each(["", "0912345678", "091234567890", "02112345678", "08123456789", "+19123456789", "0912abc6789", "98912345678"])(
    "refuses %s",
    (input) => {
      expect(normalizeMobile(input)).toBeNull();
    },
  );

  it("formats E.164", () => {
    expect(mobileToE164("09123456789")).toBe("+989123456789");
  });
});
